package org.leviatanplatform.dodgeandinterceptorsimulator.visualizer.model;

public class PixelCoordinates {

    private int x;
    private int y;

    public PixelCoordinates(int x, int y) {
        this.x = x;
        this.y = y;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }
}
